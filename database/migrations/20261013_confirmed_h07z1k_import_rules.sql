-- PROSOEL Costes | 2026-10-13
-- Safe post-import normalization for previously reviewed H07Z1-K purchases.
-- No data in orders/order_lines is overwritten. Existing purchase reviews are not touched.
-- Rule keys are (supplier, exact original reference, whitespace-normalized original description).

create table if not exists private.confirmed_import_normalization_rules (
  id bigint generated by default as identity primary key,
  supplier_id bigint not null references public.suppliers(id),
  source_reference_key text not null,
  source_description_key text not null,
  target_reference text not null,
  target_description text not null,
  evidence_lines integer not null check (evidence_lines>0),
  family text not null default 'H07Z1-K',
  approved_source text not null,
  approved_at timestamptz not null default now(),
  active boolean not null default true,
  unique (supplier_id,source_reference_key,source_description_key)
);

create table if not exists private.import_normalization_results (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id),
  order_line_id bigint not null unique references public.order_lines(id),
  rule_id bigint references private.confirmed_import_normalization_rules(id),
  decision text not null check(decision in('applied','already_standard','price_alert','no_confirmed_rule')),
  detail text not null,
  processed_by text not null,
  created_at timestamptz not null default now()
);

create index if not exists ix_import_norm_results_order on private.import_normalization_results(order_id,decision);
revoke all on table private.confirmed_import_normalization_rules from public,anon,authenticated;
revoke all on table private.import_normalization_results from public,anon,authenticated;

-- Convert historical, already-reviewed lines to exact-source rules ONLY if original
-- section and color independently confirm the effective description.
-- Not all historical reviews become general rules (notably wrong original sizes).
with b as (
 select e.id,s.id supplier_id,s.name supplier_name,
 upper(regexp_replace(btrim(coalesce(e.supplier_reference_source,'')),'[[:space:]]+','','g')) source_reference_key,
 upper(regexp_replace(btrim(e.description_source),'[[:space:]]+',' ','g')) source_description_key,
 e.supplier_reference target_reference,e.description_original target_description,
 replace((regexp_match(e.description_original,
 '^Hilo Flexible Libre Halógenos H07Z1-K ([0-9.]+)mm2 '))[1],',','.') target_section,
 (regexp_match(e.description_original,'^Hilo Flexible Libre Halógenos H07Z1-K [0-9.]+mm2 (.*)$'))[1] target_color,
 replace(coalesce(
 (regexp_match(upper(e.description_source),'1X[[:space:]]*([0-9]+(?:[,.][0-9]+)?)'))[1],
 (regexp_match(upper(e.description_source),'H07Z1[ -]?K(?:[[:space:]]*\(AS\))?[[:space:]]*([0-9]+(?:[,.][0-9]+)?)'))[1],
 (regexp_match(upper(e.description_source),'([0-9]+(?:[,.][0-9]+)?)[[:space:]]*MM'))[1]),',','.') source_section,
 e.description_source
 from public.order_lines_effective e
 join public.orders o on o.id=e.order_id
 join public.suppliers s on s.id=o.supplier_id
 where e.line_review_revision>0
 and e.description_original like 'Hilo Flexible Libre Halógenos H07Z1-K %'
 and e.usable_for_prices
 and e.line_kind not in('environmental_fee','freight','service')
), check_color as (
 select *,
 case
 when upper(description_source) ~ 'GRIS[[:space:]]+VERDE'
  then case when supplier_name='GRUPO RIAS'
   and source_reference_key='H07Z1K2,5GRI' and target_color='GRIS' then 'GRIS' else null end
 when upper(description_source) ~ 'AZUL.*NEGRO|NEGRO.*AZUL' then null
 when upper(description_source) ~ 'AMARIL+O[[:space:]/-]*VERDE|AM[./ -]*VERDE|AM-VD|A/V' then 'AMARILLO VERDE'
 when upper(description_source) ~ 'NEGRO|NG[.]BOB' then 'NEGRO'
 when upper(description_source) ~ 'AZUL|AZ[.]BOB' then 'AZUL'
 when upper(description_source) ~ 'MARR[ÓO]N' then 'MARRON'
 when upper(description_source) ~ 'GRIS' then 'GRIS'
 else null end source_color,
 replace((regexp_match(source_reference_key,'^H07Z1-?K([0-9]+(?:,[0-9]+)?)[A-Z]+$'))[1],',','.') reference_section
 from b
), safe as (
 select * from check_color
 where source_section=target_section
 and source_color=target_color
 and (reference_section is null or reference_section=target_section)
 and upper(description_source) not like '%RZ1-K%'
 and upper(description_source) not like '%AFIREFACIL%'
), unambiguous as (
 select supplier_id,source_reference_key,source_description_key,
 min(target_reference) target_reference,min(target_description) target_description,
 count(*)::integer evidence_lines
 from safe
 group by supplier_id,source_reference_key,source_description_key
 having count(distinct (target_reference,target_description))=1
)
insert into private.confirmed_import_normalization_rules
 (supplier_id,source_reference_key,source_description_key,target_reference,target_description,
 evidence_lines,approved_source)
select supplier_id,source_reference_key,source_description_key,target_reference,target_description,
 evidence_lines,'PROSOEL | auditoría confirmada H07Z1-K 2026-10-13'
from unambiguous
on conflict(supplier_id,source_reference_key,source_description_key) do nothing;

-- Only callable after an authenticated, admin-authorized import.
-- Reuse the official review function for version control, audit and queue reconciliation.
create or replace function private.apply_confirmed_import_rules(p_order_id bigint)
returns jsonb
language plpgsql security definer set search_path to ''
as $norm$
declare
 actor text:=lower(coalesce(auth.jwt()->>'email',''));
 allowed boolean;
 owner_email text;
 rec record;
 rule_rec record;
 baseline numeric;
 comparison_count integer;
 old_price numeric;
 normal_status text;
 detail_text text;
 applied_count integer:=0;
 alerts integer:=0;
 pending integer:=0;
begin
 select exists(select 1 from public.app_users u where lower(u.email)=actor
   and u.active and u.role='admin') into allowed;
 select lower(imported_by) into owner_email from public.orders where id=p_order_id;
 if not coalesce(allowed,false) or auth.uid() is null or owner_email is distinct from actor then
  raise exception 'Normalización: pedido no autorizado' using errcode='42501';
 end if;

 for rec in
  select l.id,l.supplier_reference,l.description_original,l.net_unit_price,l.line_kind,
   o.supplier_id
  from public.order_lines l join public.orders o on o.id=l.order_id
  where l.order_id=p_order_id order by l.id
 loop
  if rec.line_kind in('environmental_fee','freight','service') then continue; end if;
  select r.* into rule_rec
  from private.confirmed_import_normalization_rules r
  where r.active and r.supplier_id=rec.supplier_id
   and r.source_reference_key=upper(regexp_replace(btrim(coalesce(rec.supplier_reference,'')),'[[:space:]]+','','g'))
   and r.source_description_key=upper(regexp_replace(btrim(rec.description_original),'[[:space:]]+',' ','g'))
  limit 1;

  if not found then
   if upper(rec.description_original) like '%H07Z1%'
     or exists(select 1 from private.confirmed_import_normalization_rules r
       where r.active and r.supplier_id=rec.supplier_id
        and r.source_reference_key=upper(regexp_replace(btrim(coalesce(rec.supplier_reference,'')),'[[:space:]]+','','g')))
   then
    insert into private.import_normalization_results
     (order_id,order_line_id,decision,detail,processed_by)
    values(p_order_id,rec.id,'no_confirmed_rule',
    'Sin coincidencia exacta con una regla aprobada. Revisión manual de sección, color y descripción.',actor);
    pending:=pending+1;
   end if;
   continue;
  end if;

  select count(*),percentile_cont(0.5) within group(order by h.net_unit_price)
   into comparison_count,baseline
  from public.order_lines_effective h
  join public.orders oh on oh.id=h.order_id
  where oh.supplier_id=rec.supplier_id and h.order_id<>p_order_id
   and h.supplier_reference=rule_rec.target_reference
   and h.description_original=rule_rec.target_description
   and h.usable_for_prices and h.net_unit_price>0
   and h.line_kind not in('environmental_fee','freight','service');
  old_price:=rec.net_unit_price;
  if old_price is null or old_price<=0 or
    (comparison_count>=3 and baseline>0 and
     (old_price>baseline*1.55 or old_price<baseline*0.60)) then
   insert into private.import_normalization_results
   (order_id,order_line_id,rule_id,decision,detail,processed_by)
   values(p_order_id,rec.id,rule_rec.id,'price_alert',
    format('Precio sin normalización automática: neto %s, mediana comparable %s, compras %s.',
       coalesce(old_price::text,'n/d'),coalesce(baseline::text,'n/d'),comparison_count),actor);
   alerts:=alerts+1;
   continue;
  end if;

  if rule_rec.target_reference is not distinct from rec.supplier_reference
    and rule_rec.target_description is not distinct from rec.description_original then
   normal_status:='already_standard';
   detail_text:='Ya contiene referencia y descripción estándar; sin revisión innecesaria.';
  else
   perform private.apply_purchase_line_review(rec.id,'correct',
      rule_rec.target_reference,rule_rec.target_description,
      'Regla H07Z1-K confirmada #'||rule_rec.id||
      ': mismo proveedor, referencia y descripción de origen previamente validados; comprobación de precio superada. No se modifica ningún dato original ni importe.',0);
   normal_status:='applied';
   detail_text:='Campos efectivos corregidos mediante revisión auditada, versión 1.';
   applied_count:=applied_count+1;
  end if;
  insert into private.import_normalization_results
    (order_id,order_line_id,rule_id,decision,detail,processed_by)
  values(p_order_id,rec.id,rule_rec.id,normal_status,detail_text,actor);
 end loop;
 return jsonb_build_object('applied',applied_count,'price_alerts',alerts,'pending',pending);
end;
$norm$;

revoke all on function private.apply_confirmed_import_rules(bigint) from public,anon;
grant execute on function private.apply_confirmed_import_rules(bigint) to authenticated;

-- Keep the RPC return contract IDENTICAL for the existing browser importer.
-- Imports, normalizes and audits in the same PostgreSQL transaction.
create or replace function public.import_new_prosoel_order(p_order jsonb)
returns table(result text, imported_order_id bigint, imported_lines integer, detail text)
language plpgsql set search_path to ''
as $rpc$
declare r record;
begin
 for r in select * from private.insert_new_prosoel_order(p_order) loop
  if r.result='imported' then
   perform private.apply_confirmed_import_rules(r.imported_order_id);
  end if;
  result:=r.result;
  imported_order_id:=r.imported_order_id;
  imported_lines:=r.imported_lines;
  detail:=r.detail;
  return next;
 end loop;
end;
$rpc$;
revoke all on function public.import_new_prosoel_order(jsonb) from public,anon;
grant execute on function public.import_new_prosoel_order(jsonb) to authenticated;
