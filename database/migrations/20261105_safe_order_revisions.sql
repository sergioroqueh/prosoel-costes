-- Actualización auditada de pedidos: identidad estable, control de concurrencia,
-- versión previa integral y conciliación de líneas con conservación de IDs.
-- Migración ya aplicada en proyecto kusbndefngttaiytcrui.
CREATE TABLE IF NOT EXISTS public.order_revision_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id bigint NOT NULL REFERENCES public.orders(id) ON DELETE RESTRICT,
  revision_number integer NOT NULL,
  old_source_sha256 char(64) NOT NULL,
  new_source_sha256 char(64) NOT NULL,
  old_source_filename text NOT NULL,
  new_source_filename text NOT NULL,
  before_order jsonb NOT NULL,
  before_lines jsonb NOT NULL,
  revised_by text NOT NULL,
  reason text NOT NULL,
  revised_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(order_id,revision_number)
);
CREATE INDEX IF NOT EXISTS idx_order_revision_history_order ON public.order_revision_history(order_id,revised_at DESC);
ALTER TABLE public.order_revision_history ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.order_revision_history FROM anon,authenticated;

CREATE OR REPLACE FUNCTION private.replace_existing_prosoel_order(p jsonb, p_expected_sha text, p_reason text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
  actor text := lower(coalesce(auth.jwt()->>'email',''));
  allowed boolean;
  original public.orders%rowtype;
  old_supplier text;
  source_hash text;
  source_name text;
  line_count integer;
  item jsonb;
  i integer := 0;
  qty numeric;
  net numeric;
  line_total numeric;
  declared numeric;
  sum_total numeric := 0;
  missing boolean := false;
  status text;
  kind text;
  mapped_ids bigint[] := ARRAY[]::bigint[];
  used_ids bigint[] := ARRAY[]::bigint[];
  matched_id bigint;
  old_line public.order_lines%rowtype;
  commercial_id bigint;
  variant_key text;
  project_key bigint;
  old_lines_snapshot jsonb;
  rev integer;
  l_added integer := 0;
  l_changed integer := 0;
  l_removed integer := 0;
  old_src_row integer;
BEGIN
  SELECT EXISTS(SELECT 1 FROM public.app_users a
    WHERE lower(a.email)=actor AND a.active AND a.role='admin') INTO allowed;
  IF auth.uid() IS NULL OR NOT coalesce(allowed,false) THEN
    RAISE EXCEPTION 'Solo administradores pueden actualizar pedidos' USING ERRCODE='42501';
  END IF;
  IF p IS NULL OR jsonb_typeof(p)<>'object' OR octet_length(p::text)>262144
     OR jsonb_typeof(p->'lines')<>'array' THEN
    RAISE EXCEPTION 'Datos del pedido inválidos o demasiado grandes';
  END IF;
  line_count := jsonb_array_length(p->'lines');
  IF line_count<1 OR line_count>250 THEN
    RAISE EXCEPTION 'Se requieren entre 1 y 250 líneas';
  END IF;
  IF length(btrim(coalesce(p_reason,'')))<5 OR length(p_reason)>1000 THEN
    RAISE EXCEPTION 'Escribe un motivo de actualización (al menos 5 caracteres)';
  END IF;
  source_hash := lower(coalesce(p->>'source_sha256',''));
  source_name := btrim(coalesce(p->>'source_filename',''));
  IF source_hash !~ '^[a-f0-9]{64}$' OR p_expected_sha !~ '^[a-f0-9]{64}$'
    OR length(source_name)<5 OR length(source_name)>240 OR lower(source_name) NOT LIKE '%.xlsx' THEN
    RAISE EXCEPTION 'Identidad de archivo XLSX inválida';
  END IF;
  IF coalesce(p->>'order_identity_status','')='conflict' THEN
    RAISE EXCEPTION 'El número del fichero no coincide con el interior del pedido';
  END IF;
  -- Bloqueo de fila y condición de concurrencia: nunca sobrescribir otra revisión.
  SELECT * INTO original FROM public.orders o
    WHERE o.order_year=(p->>'order_year')::integer
      AND o.order_number=(p->>'order_number')::integer
      AND coalesce(o.order_subnumber,'')=coalesce(p->>'order_subnumber','')
    ORDER BY o.id LIMIT 1 FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'No existe el pedido que se pretende actualizar'; END IF;
  IF btrim(original.source_sha256::text)<>p_expected_sha THEN
    RAISE EXCEPTION 'El pedido ha cambiado desde la vista previa. Vuelve a seleccionar el fichero';
  END IF;
  IF original.source_sha256::text=source_hash THEN
    RETURN jsonb_build_object('result','duplicate','order_id',original.id);
  END IF;
  IF EXISTS(SELECT 1 FROM public.orders x WHERE x.source_sha256=source_hash AND x.id<>original.id) THEN
    RAISE EXCEPTION 'Este Excel ya pertenece a otro pedido: no se puede sustituir';
  END IF;
  SELECT s.name INTO old_supplier FROM public.suppliers s WHERE s.id=original.supplier_id;
  IF lower(btrim(coalesce(old_supplier,'')))<>lower(btrim(coalesce(p->>'supplier',''))) THEN
    RAISE EXCEPTION 'El proveedor no coincide con el pedido original. Requiere revisión manual';
  END IF;
  IF original.order_date IS DISTINCT FROM (p->>'order_date')::date THEN
    RAISE EXCEPTION 'La fecha del pedido ha cambiado. Requiere revisión manual de identidad';
  END IF;
  -- Prevalidación de todas las líneas y total antes de tocar datos existentes.
  FOR item IN SELECT value FROM jsonb_array_elements(p->'lines') LOOP
    i := i+1;
    IF jsonb_typeof(item)<>'object' THEN RAISE EXCEPTION 'Línea % inválida',i; END IF;
    qty := (item->>'quantity')::numeric;
    IF qty IS NULL OR qty=0 OR abs(qty)>10000000
       OR nullif(btrim(coalesce(item->>'description_original','')),'') IS NULL THEN
      RAISE EXCEPTION 'Cantidad o descripción inválida en línea %',i;
    END IF;
    variant_key := lower(coalesce(item->>'commercial_variant_key',''));
    IF variant_key !~ '^[a-f0-9]{64}$' THEN
      RAISE EXCEPTION 'Huella comercial inválida en línea %',i;
    END IF;
    net := (item->>'net_unit_price')::numeric;
    line_total := (item->>'total_price')::numeric;
    IF net IS NULL OR line_total IS NULL THEN missing:=true;
    ELSE sum_total:=sum_total+line_total; END IF;
  END LOOP;
  declared := (p->>'declared_total')::numeric;
  status := CASE WHEN missing THEN 'incomplete_prices'
    WHEN declared IS NOT NULL AND abs(round(sum_total,2)-round(declared,2))<=0.01
      THEN 'valid' ELSE 'total_mismatch' END;
  -- Dos pasadas: reservar todos los materiales idénticos antes de emparejar
  -- ediciones por posición. Una nueva fila intercalada no puede capturar un ID previo.
  i:=0;
  FOR item IN SELECT value FROM jsonb_array_elements(p->'lines') LOOP
    i:=i+1;
    matched_id:=NULL;
    old_src_row:=coalesce((item->>'source_row')::integer,i);
    SELECT x.id INTO matched_id FROM public.order_lines x
      WHERE x.order_id=original.id AND NOT (x.id=ANY(used_ids))
        AND x.supplier_reference IS NOT DISTINCT FROM (item->>'supplier_reference')
        AND x.description_original=(item->>'description_original')
      ORDER BY abs(x.source_row-old_src_row),x.id LIMIT 1;
    mapped_ids:=array_append(mapped_ids,matched_id);
    IF matched_id IS NOT NULL THEN used_ids:=array_append(used_ids,matched_id); END IF;
  END LOOP;
  FOR i IN 1..line_count LOOP
    IF mapped_ids[i] IS NULL THEN
      matched_id:=NULL;
      SELECT x.id INTO matched_id FROM public.order_lines x
        WHERE x.order_id=original.id AND x.line_number=i AND NOT (x.id=ANY(used_ids))
        LIMIT 1;
      mapped_ids[i]:=matched_id;
      IF matched_id IS NOT NULL THEN used_ids:=array_append(used_ids,matched_id); END IF;
    END IF;
  END LOOP;
  -- No perder decisiones de normalización ni revisiones externas.
  FOR old_line IN SELECT * FROM public.order_lines x WHERE x.order_id=original.id LOOP
    IF NOT (old_line.id=ANY(used_ids)) THEN
      IF EXISTS(SELECT 1 FROM public.purchase_line_overrides o WHERE o.order_line_id=old_line.id)
        OR EXISTS(SELECT 1 FROM private.import_normalization_results n WHERE n.order_line_id=old_line.id)
        OR EXISTS(SELECT 1 FROM public.review_issues r WHERE r.order_line_id=old_line.id) THEN
        RAISE EXCEPTION 'La línea % tiene revisiones asociadas y no se puede eliminar automáticamente',old_line.line_number;
      END IF;
      l_removed:=l_removed+1;
    END IF;
  END LOOP;
  i:=0;
  FOR item IN SELECT value FROM jsonb_array_elements(p->'lines') LOOP
    i:=i+1;
    matched_id:=mapped_ids[i];
    IF matched_id IS NOT NULL THEN
      SELECT * INTO old_line FROM public.order_lines x WHERE x.id=matched_id;
      IF (old_line.supplier_reference IS DISTINCT FROM (item->>'supplier_reference')
         OR old_line.description_original IS DISTINCT FROM (item->>'description_original'))
        AND (EXISTS(SELECT 1 FROM public.purchase_line_overrides o WHERE o.order_line_id=matched_id)
         OR EXISTS(SELECT 1 FROM private.import_normalization_results n WHERE n.order_line_id=matched_id)
         OR EXISTS(SELECT 1 FROM public.review_issues r WHERE r.order_line_id=matched_id)) THEN
        RAISE EXCEPTION 'La línea original % tiene revisiones. No se puede cambiar su identidad automáticamente',old_line.line_number;
      END IF;
    END IF;
  END LOOP;
  SELECT coalesce(jsonb_agg(to_jsonb(x) ORDER BY x.line_number),'[]'::jsonb)
    INTO old_lines_snapshot FROM public.order_lines x WHERE x.order_id=original.id;
  SELECT coalesce(max(r.revision_number),0)+1 INTO rev FROM public.order_revision_history r
    WHERE r.order_id=original.id;
  INSERT INTO public.order_revision_history(
    order_id,revision_number,old_source_sha256,new_source_sha256,
    old_source_filename,new_source_filename,before_order,before_lines,revised_by,reason)
  VALUES(original.id,rev,original.source_sha256,source_hash,
    original.source_filename,source_name,to_jsonb(original),old_lines_snapshot,actor,btrim(p_reason));
  -- Soltar únicamente líneas sin referencias ajenas. Las demás conservan su ID.
  DELETE FROM public.order_lines x WHERE x.order_id=original.id
    AND NOT (x.id=ANY(used_ids));
  UPDATE public.order_lines SET line_number=-line_number WHERE order_id=original.id;
  i:=0;
  FOR item IN SELECT value FROM jsonb_array_elements(p->'lines') LOOP
    i:=i+1;
    matched_id:=mapped_ids[i];
    variant_key:=lower(item->>'commercial_variant_key');
    INSERT INTO public.commercial_items(
      supplier_id,supplier_reference,commercial_variant_key,preferred_description,match_status)
    VALUES(original.supplier_id,item->>'supplier_reference',variant_key,item->>'description_original','pending')
    ON CONFLICT(supplier_id,commercial_variant_key) DO NOTHING;
    SELECT x.id INTO commercial_id FROM public.commercial_items x
      WHERE x.supplier_id=original.supplier_id AND x.commercial_variant_key=variant_key;
    IF commercial_id IS NULL THEN RAISE EXCEPTION 'No se resolvió material en la línea %',i; END IF;
    qty:=(item->>'quantity')::numeric;
    net:=(item->>'net_unit_price')::numeric;
    line_total:=(item->>'total_price')::numeric;
    kind:=coalesce(nullif(item->>'line_kind',''),'unknown');
    IF kind NOT IN ('unknown','environmental_fee','freight','service','service_candidate') THEN
      kind:='unknown';
    END IF;
    IF matched_id IS NULL THEN
      INSERT INTO public.order_lines(
        order_id,line_number,source_row,commercial_item_id,quantity,supplier_reference,
        description_original,pvp,discount_raw,discount_components_raw,
        net_unit_price,total_price,price_validation_status,price_validation_detail,
        line_kind,line_kind_confidence,line_kind_reasons,line_kind_review_status)
      VALUES(
        original.id,i,coalesce((item->>'source_row')::integer,i),commercial_id,qty,
        item->>'supplier_reference',item->>'description_original',(item->>'pvp')::numeric,
        item->>'discount_raw',
        CASE WHEN jsonb_typeof(item->'discount_components_raw')='array' THEN item->'discount_components_raw' ELSE '[]'::jsonb END,
        net,line_total,
        CASE WHEN net IS NULL OR line_total IS NULL THEN 'incomplete'
          WHEN abs(round(qty*net,2)-round(line_total,2))<=0.01 THEN 'valid' ELSE 'mismatch' END,
        jsonb_build_object('calculated_total',CASE WHEN net IS NULL THEN NULL ELSE round(qty*net,2) END,'observed_total',line_total),
        kind,CASE WHEN kind='environmental_fee' THEN 0.995 WHEN kind='freight' THEN 0.99
          WHEN kind='service' THEN 0.97 WHEN kind='service_candidate' THEN 0.80 ELSE 0 END,
        CASE WHEN jsonb_typeof(item->'line_kind_reasons')='array' THEN item->'line_kind_reasons' ELSE '[]'::jsonb END,
        CASE WHEN kind IN ('environmental_fee','freight','service') THEN 'auto' ELSE 'pending' END);
      l_added:=l_added+1;
    ELSE
      SELECT * INTO old_line FROM public.order_lines x WHERE x.id=matched_id;
      IF old_line.quantity IS DISTINCT FROM qty OR old_line.net_unit_price IS DISTINCT FROM net
        OR old_line.total_price IS DISTINCT FROM line_total OR old_line.source_row IS DISTINCT FROM coalesce((item->>'source_row')::integer,i)
        OR old_line.supplier_reference IS DISTINCT FROM (item->>'supplier_reference')
        OR old_line.description_original IS DISTINCT FROM (item->>'description_original')
        OR abs(old_line.line_number) IS DISTINCT FROM i THEN
        l_changed:=l_changed+1;
      END IF;
      UPDATE public.order_lines SET
        line_number=i,source_row=coalesce((item->>'source_row')::integer,i),
        commercial_item_id=commercial_id,
        material_id=CASE WHEN commercial_item_id=commercial_id THEN material_id ELSE NULL END,
        quantity=qty,supplier_reference=item->>'supplier_reference',
        description_original=item->>'description_original',
        pvp=(item->>'pvp')::numeric,discount_raw=item->>'discount_raw',
        discount_components_raw=CASE WHEN jsonb_typeof(item->'discount_components_raw')='array' THEN item->'discount_components_raw' ELSE '[]'::jsonb END,
        net_unit_price=net,total_price=line_total,
        price_validation_status=CASE WHEN net IS NULL OR line_total IS NULL THEN 'incomplete'
          WHEN abs(round(qty*net,2)-round(line_total,2))<=0.01 THEN 'valid' ELSE 'mismatch' END,
        price_validation_detail=jsonb_build_object(
          'calculated_total',CASE WHEN net IS NULL THEN NULL ELSE round(qty*net,2) END,'observed_total',line_total),
        line_kind=kind,
        line_kind_confidence=CASE WHEN kind='environmental_fee' THEN 0.995 WHEN kind='freight' THEN 0.99
          WHEN kind='service' THEN 0.97 WHEN kind='service_candidate' THEN 0.80 ELSE 0 END,
        line_kind_reasons=CASE WHEN jsonb_typeof(item->'line_kind_reasons')='array' THEN item->'line_kind_reasons' ELSE '[]'::jsonb END,
        line_kind_review_status=CASE WHEN commercial_item_id=commercial_id THEN line_kind_review_status
          WHEN kind IN ('environmental_fee','freight','service') THEN 'auto' ELSE 'pending' END
      WHERE id=matched_id;
    END IF;
  END LOOP;
  project_key:=original.project_id;
  IF nullif(btrim(coalesce(p->>'project','')),'') IS NOT NULL THEN
    SELECT id INTO project_key FROM public.projects WHERE name=p->>'project' ORDER BY id LIMIT 1;
    IF project_key IS NULL THEN
      INSERT INTO public.projects(name,address) VALUES(p->>'project',nullif(p->>'project_address',''))
      RETURNING id INTO project_key;
    END IF;
  END IF;
  UPDATE public.orders SET
    source_sha256=source_hash,source_filename=source_name,
    declared_total=declared,validation_status=status,
    project_id=project_key,responsible=p->>'responsible',
    supplier_contact=p->>'supplier_contact',supplier_email=p->>'supplier_email',
    project_contact=p->>'project_contact',unit_header=p->>'unit_header',
    template_variant=p->>'template_variant'
  WHERE id=original.id;
  RETURN jsonb_build_object('result','updated','order_id',original.id,'revision',rev,
    'lines',line_count,'added',l_added,'changed',l_changed,'removed',l_removed,'validation',status);
END;
$function$
;

REVOKE ALL ON FUNCTION private.replace_existing_prosoel_order(jsonb,text,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION private.replace_existing_prosoel_order(jsonb,text,text) TO authenticated;

CREATE OR REPLACE FUNCTION public.update_existing_prosoel_order(p_order jsonb, p_expected_sha text, p_reason text)
 RETURNS jsonb
 LANGUAGE sql
 SET search_path TO ''
AS $function$ SELECT private.replace_existing_prosoel_order(p_order,p_expected_sha,p_reason); $function$
;

REVOKE ALL ON FUNCTION public.update_existing_prosoel_order(jsonb,text,text) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.update_existing_prosoel_order(jsonb,text,text) TO authenticated;
